/**
 * Unified Theme System
 *
 * Imports all parsed design tokens and provides helpers for applying them
 * as CSS custom properties. Works with both React components and Web Components.
 */

import { tokens as colors } from '../tokens/colors.parsed';
import { tokens as typography } from '../tokens/typography.parsed';
import { tokens as shadows } from '../tokens/shadows.parsed';

/**
 * Unified theme object containing all design tokens
 */
export const theme = {
  colors,
  typography,
  shadows,
} as const;

/**
 * Apply theme tokens as CSS custom properties to :root
 * This makes tokens available globally as CSS variables
 *
 * @param theme - Theme object containing colors, typography, and shadows
 * @example
 * ```tsx
 * import { applyTheme, theme } from './theme';
 * applyTheme(theme);
 * // Now use: var(--color-text-primary) in CSS
 * ```
 */
export function applyTheme(themeObj: typeof theme): void {
  const root = document.documentElement;

  // Apply color tokens
  Object.entries(themeObj.colors).forEach(([key, value]) => {
    root.style.setProperty(`--${key}`, value as string);
  });

  // Apply typography tokens
  Object.entries(themeObj.typography).forEach(([key, value]) => {
    if (typeof value === 'object' && value !== null) {
      // Composite typography styles (e.g., font-heading-lg)
      Object.entries(value).forEach(([prop, val]) => {
        root.style.setProperty(`--${key}-${prop}`, val as string);
      });
    } else {
      // Primitive typography tokens (e.g., font-size-base)
      root.style.setProperty(`--${key}`, value as string);
    }
  });

  // Apply shadow tokens
  Object.entries(themeObj.shadows).forEach(([key, value]) => {
    root.style.setProperty(`--${key}`, value as string);
  });
}

/**
 * Remove theme CSS custom properties from :root
 * Useful for cleanup or theme switching
 */
export function removeTheme(themeObj: typeof theme): void {
  const root = document.documentElement;

  Object.keys(themeObj.colors).forEach((key) => {
    root.style.removeProperty(`--${key}`);
  });

  Object.entries(themeObj.typography).forEach(([key, value]) => {
    if (typeof value === 'object' && value !== null) {
      Object.keys(value).forEach((prop) => {
        root.style.removeProperty(`--${key}-${prop}`);
      });
    } else {
      root.style.removeProperty(`--${key}`);
    }
  });

  Object.keys(themeObj.shadows).forEach((key) => {
    root.style.removeProperty(`--${key}`);
  });
}

/**
 * Get all CSS custom property names generated by the theme
 * Useful for debugging or documentation
 */
export function getThemeVariableNames(themeObj: typeof theme): string[] {
  const variables: string[] = [];

  Object.keys(themeObj.colors).forEach((key) => {
    variables.push(`--${key}`);
  });

  Object.entries(themeObj.typography).forEach(([key, value]) => {
    if (typeof value === 'object' && value !== null) {
      Object.keys(value).forEach((prop) => {
        variables.push(`--${key}-${prop}`);
      });
    } else {
      variables.push(`--${key}`);
    }
  });

  Object.keys(themeObj.shadows).forEach((key) => {
    variables.push(`--${key}`);
  });

  return variables.sort();
}

export default theme;
